def main():
    cv2_dir = os.path.dirname(cv2.__file__)
    sections = [
        ("Electron (MIT). Chromium and its components: see LICENSES.chromium.html next to the app executable.",
         read(os.path.join(ROOT, "node_modules", "electron", "dist", "LICENSE"))),
        ("koffi (MIT)", read(os.path.join(ROOT, "node_modules", "koffi", "LICENSE.txt"))),
        ("OpenCV (Apache-2.0; full text at the end). opencv-python packaging (MIT):",
         read(os.path.join(cv2_dir, "LICENSE.txt"))),
        ("Components redistributed inside the OpenCV wheel. The FFmpeg plugin DLL is NOT shipped "
         "(removed in backend/smartscreen_ai.spec).",
         read(os.path.join(cv2_dir, "LICENSE-3RD-PARTY.txt"))),
        ("NumPy (BSD-3-Clause, with bundled components)",
         read(os.path.join(dist_info(numpy, "numpy"), "LICENSE.txt"))),
        ("Python runtime (PSF License), bundled by PyInstaller",
         read(os.path.join(sys.base_prefix, "LICENSE.txt"))),
        ("PyInstaller bootloader (GPL-2.0 with the bootloader exception: the bundled program may use any license)",
         read(os.path.join(dist_info(PyInstaller, "pyinstaller"), "licenses", "COPYING.txt"))),
        ("YuNet face detection model, face_detection_yunet_2023mar.onnx (MIT, OpenCV Zoo)", YUNET_MIT),
        ("SFace face recognition model, face_recognition_sface_2021dec.onnx (Apache-2.0, OpenCV Zoo)",
         "Licensed under the Apache License, Version 2.0 (full text below)."),
        ("Apache License 2.0 (OpenCV, SFace)", apache_text()),
    ]
    rule = "=" * 78
    parts = [
        "SmartScreen Privacy Suite - third-party notices",
        "",
        "SmartScreen itself is MIT licensed (see LICENSE.txt). It ships the components below.",
        "Generated by scripts/third_party_notices.py; do not edit by hand.",
    ]
    for title, body in sections:
        parts += ["", rule, title, rule, "", body]
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(parts) + "\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes)")


if __name__ == "__main__":
    main()
