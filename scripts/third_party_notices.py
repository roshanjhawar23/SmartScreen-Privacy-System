"""Regenerate THIRD_PARTY_NOTICES.txt from the license files of what actually ships.

Run from the repo root before `npm run build` whenever a shipped dependency changes:
    python scripts/third_party_notices.py
The list of shipped pieces is kept in sync with docs/DEPENDENCIES.md.
"""

import os
import sys

import cv2
import numpy
import PyInstaller

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.txt")


def read(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read().strip()


def dist_info(module, name):
    site = os.path.dirname(os.path.dirname(module.__file__))
    for entry in os.listdir(site):
        if entry.lower().startswith(name.lower() + "-") and entry.endswith(".dist-info"):
            return os.path.join(site, entry)
    raise SystemExit(f"dist-info for {name} not found")


def apache_text():
    text = read(os.path.join(ROOT, "node_modules", "playwright-core", "LICENSE"))
    end = text.index("END OF TERMS AND CONDITIONS") + len("END OF TERMS AND CONDITIONS")
    start = text.index("Apache License")
    return text[start:end]


